const NUMBER_WORDS = ['Zero', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten', 'Eleven', 'Twelve'];
/** 'Nine' for 9; digits above twelve. */
export const numberWord = (n: number): string => NUMBER_WORDS[n] ?? String(n);

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/** '21:50' → '9:50 pm' (en-AU 12-hour, lower-case like the cover clock). */
export function formatWallTime(hhmm: string): string {
  const [h, m] = hhmm.split(':').map(Number);
  return `${h % 12 === 0 ? 12 : h % 12}:${String(m).padStart(2, '0')} ${h < 12 ? 'am' : 'pm'}`;
}

/** '2030-12-26' → 'Dec 26, 2030' (shown upper-case by CSS: 'DEC 26, 2030'). */
export function formatCoverDate(date: string): string {
  const [y, m, d] = date.split('-').map(Number);
  return `${MONTHS[m - 1]} ${String(d).padStart(2, '0')}, ${y}`;
}

/** 'Dec 26, 2030 — Jan 03, 2031' */
export const formatTripRange = (start: string, end: string): string => `${formatCoverDate(start)} — ${formatCoverDate(end)}`;

